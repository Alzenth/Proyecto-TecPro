GO

-- Detalle Venta:
CREATE SEQUENCE Seq_DETALLE_VENTA_ID
    START WITH 0
    INCREMENT BY 1;
GO

CREATE TABLE DETALLE_VENTA (
    ID_DETALLE_VENTA CHAR(5) DEFAULT ('DV' + RIGHT('000' + CAST(NEXT VALUE FOR Seq_DETALLE_VENTA_ID AS VARCHAR(3)), 3)) NOT NULL,
    ID_VENTA CHAR(4) NOT NULL, 
	-- Ampliado a CHAR(5)
    ID_PRODUCTO CHAR(5) NOT NULL,
    CANTIDAD INT NOT NULL,
    PRECIO_UNITARIO DECIMAL(10,2) NOT NULL,
    PRECIO DECIMAL(10, 2) NOT NULL, 

    CONSTRAINT PK_ID_DETALLE_VENTA PRIMARY KEY (ID_DETALLE_VENTA),
    CONSTRAINT FK_DV_ID_VENTA FOREIGN KEY (ID_VENTA) REFERENCES VENTA(ID_VENTA),
    CONSTRAINT FK_DV_ID_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO),
    CONSTRAINT CHK_DV_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CHK_DV_PRECIO_UNITARIO CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CHK_DV_PRECIO CHECK (PRECIO >= 0)
);
GO

