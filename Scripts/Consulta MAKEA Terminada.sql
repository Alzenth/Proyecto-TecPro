    START WITH 0
    INCREMENT BY 1;
GO

CREATE TABLE VENTA (
    ID_VENTA CHAR(4) DEFAULT ('V' + RIGHT('000' + CAST(NEXT VALUE FOR Seq_VENTA_ID AS VARCHAR(3)), 3)) NOT NULL,
    ID_CLIENTE CHAR(4) NOT NULL,
    FECHA_HORA DATETIME DEFAULT GETDATE() NOT NULL, 
    IGV DECIMAL(10,2) NOT NULL, 

    CONSTRAINT PK_ID_VENTA PRIMARY KEY (ID_VENTA),
    CONSTRAINT FK_VE_ID_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE)
