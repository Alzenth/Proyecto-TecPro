package gui;

public class Empleado {
	private int id_empleado;
	private String nombre, Cargo, apellido;
	public Empleado(int id_empleado, String nombre, String cargo, String apellido) {
		super();
		this.id_empleado = id_empleado;
		this.nombre = nombre;
		Cargo = cargo;
		this.apellido = apellido;
	}
	
	
}
