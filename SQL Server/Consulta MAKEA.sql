CREATE PROCEDURE SP_Agregar_Admin
    @ID_ADMIN CHAR(4),
    @NOM VARCHAR(100),
    @APE VARCHAR(100),
    @CORREO VARCHAR(100),
    @PASS VARCHAR(8),
    @DOC_DNI INT,
    @F_NAC DATE,
    @TELF VARCHAR(9)
AS 
BEGIN
    INSERT INTO ADMINISTRADOR (ID_ADMINISTRADOR, NOMBRES, APELLIDOS, EMAIL, CONTRASEÑA, DNI, FECHA_NACIMIENTO, TELEFONO) 
    VALUES (@ID_ADMIN, @NOM, @APE, @CORREO, @PASS, @DOC_DNI, @F_NAC, @TELF);
END;
GO

