    'Chocotejas de Pisco Sour', 
    'Chocoteja', 
    'Deliciosa chocoteja llena de manjar', 
    200, 
    2.50, 
    '2026-06-25',  
    '2026-07-25'; 
GO


CREATE PROCEDURE SP_Listar_Productos
AS 
BEGIN
    SELECT * FROM PRODUCTO;
END;
GO

