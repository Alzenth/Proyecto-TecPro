CREATE TABLE PRODUCTO (
	ID_PRODUCTO CHAR (4) NOT NULL PRIMARY KEY,
	NOMBRE VARCHAR(100) NOT NULL,
	CATEGORIA VARCHAR(50) NOT NULL,
	DESCRIPCION VARCHAR(255) NOT NULL,
	STOCK INT NOT NULL,
	PRECIO DECIMAL(10, 2) NOT NULL,
	Fecha_Creacion DATE NOT NULL,
	Fecha_Expiracion DATE NOT NULL
);
GO
CREATE PROCEDURE SP_Agregar_Producto
    @ID_PROD CHAR(4),
    @NOM VARCHAR(100),
    @CAT VARCHAR(50),
    @DESCR VARCHAR(255),
    @STK INT,
    @PREC DECIMAL(10,2),
    @F_CREA DATE,
    @F_EXP DATE
    
AS 
BEGIN
    INSERT INTO PRODUCTO (ID_PRODUCTO, NOMBRE, CATEGORIA, DESCRIPCION, STOCK, PRECIO, Fecha_Creacion, Fecha_Expiracion) 
    VALUES (@ID_PROD, @NOM, @CAT, @DESCR, @STK, @PREC, @F_CREA, @F_EXP);
END;
GO


EXEC SP_Agregar_Producto 
